DROP FUNCTION IF EXISTS public.list_configured_cameras(uuid);

CREATE FUNCTION public.list_configured_cameras(target_request_id uuid)
RETURNS TABLE(stream_url text, name text, updated_at timestamptz, is_active boolean)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
  SELECT catalog.stream_url,
         COALESCE(catalog.name, 'Cámara disponible'),
         device.updated_at,
         COALESCE(device.is_active, false)
  FROM public.camera_catalog AS catalog
  LEFT JOIN public.camera_devices AS device
    ON device.stream_url = catalog.stream_url
   AND device.request_id = target_request_id
  WHERE public.is_admin()
  ORDER BY COALESCE(device.is_active, false) DESC,
           device.updated_at DESC NULLS LAST,
           catalog.created_at,
           catalog.stream_url;
$function$;

CREATE OR REPLACE FUNCTION public.set_camera_active(
  target_request_id uuid,
  target_stream_url text,
  target_is_active boolean
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'No autorizado';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.camera_catalog WHERE stream_url = target_stream_url) THEN
    RAISE EXCEPTION 'Cámara no encontrada';
  END IF;

  INSERT INTO public.camera_devices (request_id, stream_url, is_active, configured_by, updated_at)
  VALUES (target_request_id, target_stream_url, target_is_active, auth.uid(), now())
  ON CONFLICT (request_id, stream_url) DO UPDATE
  SET is_active = EXCLUDED.is_active,
      configured_by = auth.uid(),
      updated_at = now();

  RETURN true;
END;
$function$;

CREATE OR REPLACE FUNCTION public.configure_camera_device(
  target_request_id uuid,
  target_stream_url text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'No autorizado';
  END IF;

  IF target_stream_url IS NULL OR trim(target_stream_url) !~* '^https?://[^[:space:]]+$' THEN
    RAISE EXCEPTION 'La dirección de la cámara debe utilizar HTTP o HTTPS';
  END IF;

  INSERT INTO public.camera_catalog (stream_url, name, created_by)
  VALUES (trim(target_stream_url), 'Cámara disponible', auth.uid())
  ON CONFLICT (stream_url) DO NOTHING;

  INSERT INTO public.camera_devices (request_id, stream_url, is_active, configured_by, updated_at)
  VALUES (target_request_id, trim(target_stream_url), true, auth.uid(), now())
  ON CONFLICT (request_id, stream_url) DO UPDATE
  SET is_active = true, configured_by = auth.uid(), updated_at = now();

  RETURN true;
END;
$function$;

CREATE OR REPLACE FUNCTION public.save_camera_assignments(
  target_request_id uuid,
  active_stream_urls text[]
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'No autorizado';
  END IF;

  INSERT INTO public.camera_catalog (stream_url, name, created_by)
  SELECT DISTINCT trim(selected_url), 'Cámara disponible', auth.uid()
  FROM unnest(COALESCE(active_stream_urls, ARRAY[]::text[])) AS selected_url
  WHERE trim(selected_url) ~* '^https?://[^[:space:]]+$'
  ON CONFLICT (stream_url) DO NOTHING;

  UPDATE public.camera_devices
  SET is_active = false,
      configured_by = auth.uid(),
      updated_at = now()
  WHERE request_id = target_request_id;

  INSERT INTO public.camera_devices (request_id, stream_url, is_active, configured_by, updated_at)
  SELECT target_request_id, trim(selected_url), true, auth.uid(), now()
  FROM unnest(COALESCE(active_stream_urls, ARRAY[]::text[])) AS selected_url
  WHERE trim(selected_url) ~* '^https?://[^[:space:]]+$'
  ON CONFLICT (request_id, stream_url) DO UPDATE
  SET is_active = true,
      configured_by = auth.uid(),
      updated_at = now();

  RETURN true;
END;
$function$;

CREATE OR REPLACE FUNCTION public.delete_camera_from_catalog(target_stream_url text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'No autorizado';
  END IF;

  IF target_stream_url IN (
    'https://iot-security.pro/api/camera/stream',
    'https://iot-security.pro/api/camera/stream2',
    'https://192.168.1.101:8080/stream',
    'https://192.168.1.102:8080/stream',
    'https://10.0.0.25:8081/video'
  ) THEN
    RAISE EXCEPTION 'Las cinco cámaras base no se pueden eliminar';
  END IF;

  DELETE FROM public.camera_devices
  WHERE lower(rtrim(trim(stream_url), '/')) = lower(rtrim(trim(target_stream_url), '/'));

  DELETE FROM public.camera_catalog
  WHERE lower(rtrim(trim(stream_url), '/')) = lower(rtrim(trim(target_stream_url), '/'));

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Dirección no encontrada';
  END IF;

  RETURN true;
END;
$function$;

CREATE OR REPLACE FUNCTION public.redeem_camera_access_code(
  target_request_id uuid,
  plain_code text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  matched_id bigint;
  matched_used_at timestamptz;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'No autorizado';
  END IF;

  SELECT id, used_at
  INTO matched_id, matched_used_at
  FROM public.camera_access_codes
  WHERE request_id = target_request_id
    AND (
      display_code = trim(plain_code)
      OR code_hash = encode(
        extensions.digest(trim(plain_code), 'sha256'),
        'hex'
      )
    )
    AND expires_at > now()
  ORDER BY created_at DESC
  LIMIT 1;

  IF matched_id IS NULL THEN
    RETURN false;
  END IF;

  IF matched_used_at IS NOT NULL THEN
    RETURN public.has_active_camera_access(target_request_id);
  END IF;

  UPDATE public.camera_access_codes
  SET used_at = now(),
      display_code = NULL
  WHERE id = matched_id;

  DELETE FROM public.camera_access_grants
  WHERE request_id = target_request_id
    AND admin_id = auth.uid();

  INSERT INTO public.camera_access_grants (
    request_id,
    admin_id,
    expires_at
  )
  VALUES (
    target_request_id,
    auth.uid(),
    now() + interval '5 minutes'
  );

  RETURN true;
END;
$function$;

DROP POLICY IF EXISTS "Propietario o admin autorizado consulta cámara"
